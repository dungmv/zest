mod javascript;
mod json;
mod xml;

pub(crate) use javascript::JavaScriptHighlighter;
pub(crate) use json::JsonHighlighter;
pub(crate) use xml::{format_xml, XmlHighlighter};

fn clamp_char_boundary_left(s: &str, mut idx: usize) -> usize {
    if idx >= s.len() {
        return s.len();
    }
    while idx > 0 && !s.is_char_boundary(idx) {
        idx -= 1;
    }
    idx
}

fn clamp_char_boundary_right(s: &str, mut idx: usize) -> usize {
    if idx >= s.len() {
        return s.len();
    }
    while idx < s.len() && !s.is_char_boundary(idx) {
        idx += 1;
    }
    idx
}
